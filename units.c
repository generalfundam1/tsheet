#define NUNITS ((int)(sizeof units / sizeof units[0]))

int units_find(const char *sym) {
    for (int i = 0; i < NUNITS; i++)
        if (!strcmp(units[i].sym, sym)) return i;
    return -1;
}

const char *units_sym(int id) { return units[id].sym; }

/* value in unit from -> value in unit to is v * a + b. -1 when the two are not the same kind. */
int units_linear(int from, int to, double *a, double *b) {
    if (units[from].cat != units[to].cat) return -1;
    *a = units[from].f / units[to].f;
    *b = (units[from].off - units[to].off) / units[to].f;
    return 0;
}
